export function aiPrompt(doc, task) {
  return (
    "Подготовь полный файл " +
    doc.name +
    " на русском языке. Тип документа: " +
    doc.kind +
    ".\n\nЗадание автора:\n" +
    (task.trim() || "Заверши документ, сохраняя его назначение и структуру.") +
    "\n\nВерни один скачиваемый файл .md или его полный текст внутри внешнего ограждения из четырёх обратных кавычек. Используй заголовки, списки и GFM-таблицы. Для каждого требования дай стабильный ID и проверяемый критерий. Верни весь результат, включая разделы без изменений.\n\nКаждая редактируемая схема — блок кода studio-diagram со строгим JSON. version:1, title, nodes и edges обязательны. Узел: уникальный строковый id, label, shape (process, start, decision, data, ellipse, database, component, umlClass). У UML-класса attributes и methods — строки, по одному члену класса на строку. Модули задаются массивом modules из объектов {id,title,color}; узел ссылается на модуль через moduleId. Расположение схемы на странице задаёт layout: width в процентах (25–100), height в пикселях (0 — авто), align (left, center, right), fit (actual, contain, width). Координаты x, y и размеры width, height необязательны. Цвета fill, stroke, textColor — #RRGGBB. Связь: id, from и to (ID узлов), необязательные label, color, fromSide/toSide (auto, left, right, top, bottom), route (orthogonal, straight, curve), points (массив {x,y}), dashed, arrow (end, none, inheritance, aggregation, composition). Новым узлам можно не задавать координаты. Сохрани существующие идентификаторы, геометрию, стили, ручные точки маршрута и неизвестные поля. Не заменяй схемы изображениями или Mermaid.\n\nПример схемы:\n" +
    fence({
      version: 1,
      title: "Обработка",
      nodes: [
        { id: "a", label: "Начало", shape: "start" },
        { id: "b", label: "Проверка", shape: "decision" },
      ],
      edges: [{ id: "ab", from: "a", to: "b" }],
    }) +
    "\n\nТекущий документ:\n\n" +
    doc.body
  );
}
